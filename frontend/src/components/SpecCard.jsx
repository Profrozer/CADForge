import { useState } from "react";

// The normalized spec — what the AI understood — shown above the result.
export default function SpecCard({ spec, meta }) {
  const [open, setOpen] = useState(true);
  const [showCode, setShowCode] = useState(false);
  if (!spec && !meta?.code) return null;

  return (
    <section className="glass px-4 py-3">
      <div className="flex items-center gap-3">
        <button
          onClick={() => setOpen(!open)}
          className="font-display text-xs font-semibold tracking-[0.22em] text-ink/90 hover:text-line transition-colors"
        >
          {open ? "▾" : "▸"} INTERPRETED SPEC
        </button>
        {meta && (
          <span className="font-mono text-[10px] text-muted">
            generated by <span className="text-amber">{meta.model}</span> via{" "}
            {meta.provider}
          </span>
        )}
        <div className="flex-1" />
        {meta?.code && (
          <button
            onClick={() => setShowCode(!showCode)}
            className="font-mono text-[10px] px-2 py-0.5 rounded border border-line/20 text-muted hover:text-line hover:border-line/50 transition-colors"
          >
            {showCode ? "HIDE CADQUERY" : "VIEW CADQUERY"}
          </button>
        )}
      </div>
      {open && spec && (
        <div className="spec-body mt-2 text-xs leading-relaxed text-ink/80 max-h-40 overflow-y-auto">
          {renderBold(spec)}
        </div>
      )}
      {showCode && meta?.code && (
        <pre className="mt-2 text-[11px] leading-relaxed font-mono text-line/85 bg-abyss/60 border border-line/10 rounded p-3 max-h-56 overflow-auto">
          {meta.code}
        </pre>
      )}
    </section>
  );
}

// Renders **bold** markdown spans as React elements — no raw HTML injection.
function renderBold(text) {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? (
      <strong key={i}>{part.slice(2, -2)}</strong>
    ) : (
      part
    ),
  );
}
